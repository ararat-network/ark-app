// A known-answer test of the core, run on the device itself: it shows that
// this build, on this processor, derives the key and makes the signature that
// the same seed gives everywhere else. The seed is one of BIP-39's own test
// vectors, 32 bytes of 0x7f, whose words are "legal winner thank year wave
// sausage worth useful ... title", and the answers were made by the SDK's
// TypeScript, which shares no code with this C. A test compares them again.
#include <string.h>

#include "ark_keystore.h"
#include "ark_sha2.h"

static const uint8_t MESSAGE[] = "ark-keystore self-check";

static const uint8_t PUBLIC_KEY[ARK_PUBLIC_KEY_LENGTH] = {
    0x03, 0xd3, 0xbc, 0x6d, 0x74, 0xed, 0x3f, 0x9a, 0x6e, 0x48, 0x77, 0xe5, 0xee, 0x12, 0xba, 0x14,
    0x3a, 0x89, 0x67, 0x28, 0xdf, 0xd4, 0x27, 0x85, 0x7a, 0xa7, 0x0d, 0xcd, 0x67, 0x54, 0x9d, 0xbf,
    0x35,
};

static const uint8_t SIGNATURE[ARK_SIGNATURE_LENGTH] = {
    0xc0, 0x14, 0x75, 0x86, 0xf6, 0x32, 0x81, 0xcc, 0xb2, 0x36, 0x1a, 0xd7, 0x16, 0x31, 0x60, 0x97,
    0xf4, 0x76, 0x20, 0x5d, 0xe3, 0x6e, 0x13, 0x12, 0x04, 0x24, 0x23, 0x20, 0xb7, 0x45, 0x07, 0x5e,
    0x7b, 0x2b, 0xba, 0x58, 0x7d, 0x5d, 0xbc, 0x5b, 0xa4, 0xda, 0xa6, 0xd3, 0xe3, 0xb4, 0x2d, 0x56,
    0x15, 0x5b, 0xcb, 0x5c, 0xd3, 0x65, 0x40, 0x64, 0xf4, 0x83, 0x32, 0x83, 0x2b, 0x12, 0x65, 0x70,
};

int ark_keystore_self_check(void) {
  uint8_t seed[ARK_SEED_LENGTH];
  uint8_t public_key[ARK_PUBLIC_KEY_LENGTH];
  uint8_t signature[ARK_SIGNATURE_LENGTH];
  memset(seed, 0x7f, sizeof seed);
  int ok = ark_keystore_public_key(seed, public_key) && memcmp(public_key, PUBLIC_KEY, sizeof public_key) == 0 &&
           ark_keystore_sign(seed, MESSAGE, sizeof MESSAGE - 1, signature) && memcmp(signature, SIGNATURE, sizeof signature) == 0;
  ark_zeroise(seed, sizeof seed);
  return ok;
}
